#!/usr/bin/env bash
# Regenerates the diagnostic reports in docs/reports/.
#
#   scripts/make-reports.sh
#
# It then runs `wikidata worklist --gaps` over the same files, which writes
# docs/reports/worklist/: the same issues grouped into things to work on, four
# ways, together with what is missing rather than wrong, one CSV per task and an
# index.
#
# For every downloaded fragment in data/ this runs `wikidata report`, which
# writes three files: a CSV table of the issues, an HTML page with a summary by
# error type and status, and an SVG bar chart of the counts.  It then writes a
# combined report over all the fragments (docs/reports/corpus.*), a report on
# the merged base (docs/reports/all.*), one on the example series file, and the
# index page docs/reports/README.md.
#
# `wikidata report` exits 1 when a base has errors, which is the normal case
# here, so the exit status of the individual runs is ignored.
set -u

cd "$(dirname "$0")/.."
WD=./.lake/build/bin/wikidata
OUT=docs/reports

if [ ! -x "$WD" ]; then
  echo "building the tool first: lake build wikidata"
  lake build wikidata || exit 1
fi

mkdir -p "$OUT"

fragments=()
for f in data/*.wdkb; do
  case "$f" in
    data/all.wdkb) continue ;;   # the merge of the others; reported on separately
  esac
  fragments+=("$f")
done

for f in "${fragments[@]}"; do
  name=$(basename "$f" .wdkb)
  "$WD" report "$f" --out "$OUT/$name" >/dev/null
done

# the examples, so the series and taxon error types appear in the reports too
"$WD" report examples/trilogy.skb --out "$OUT/trilogy" >/dev/null
"$WD" report examples/defects.skb --out "$OUT/defects" >/dev/null
"$WD" report examples/taxa-defects.tkb --out "$OUT/taxa-defects" >/dev/null

# one combined table over every fragment, and one for the merged base
"$WD" report "${fragments[@]}" --out "$OUT/corpus" >/dev/null
"$WD" report data/all.wdkb --out "$OUT/all" >/dev/null

# the worklist: the same issues grouped into things to work on — by error type,
# by file, by layer and by kind of work, plus one CSV per task
"$WD" worklist "${fragments[@]}" examples/defects.skb examples/taxa-defects.tkb \
  --gaps --out "$OUT/worklist" >/dev/null

# the repair worklist: what `wikidata fix` would do to each fragment
{
  echo "# What \`wikidata fix\` does to the corpus"
  echo
  echo "Generated by \`scripts/make-reports.sh\`.  For each fragment the repair engine"
  echo "is offered one action per issue and performs only the ones it can check:"
  echo "the candidate must answer every question about the declared items exactly as"
  echo "the base did and must carry no new error.  Everything destructive is left as a"
  echo "\`review\` action for a human.  Nothing here is written back to \`data/\`."
  echo
  for f in "${fragments[@]}" examples/defects.skb; do
    echo '```'
    "$WD" fix "$f"
    echo '```'
    echo
  done
} > "$OUT/FIXES.md"

python3 docs/make_report_index.py

echo "wrote $OUT"
