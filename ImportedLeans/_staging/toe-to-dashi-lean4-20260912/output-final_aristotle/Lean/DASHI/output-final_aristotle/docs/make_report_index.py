#!/usr/bin/env python3
"""Builds docs/reports/README.md from the CSV files `wikidata report` wrote.

This script invents nothing: every number below is counted from the rows of the
generated CSV files, which the tool produced from the knowledge bases.  Run it
through scripts/make-reports.sh, which generates those files first.
"""

import csv
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "docs", "reports")

# the reports that are aggregates rather than one fragment
SPECIAL = {"corpus", "all"}


def read_rows(path):
    with open(path, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    return [r for r in rows if r.get("code")]


def main():
    names = sorted(
        f[:-4] for f in os.listdir(OUT) if f.endswith(".csv")
    )
    per_file = {n: read_rows(os.path.join(OUT, n + ".csv")) for n in names}

    lines = []
    lines.append("# Diagnostic reports")
    lines.append("")
    lines.append(
        "Generated by `scripts/make-reports.sh`, which runs `wikidata report` over "
        "the downloaded fragments in [`data/`](../../data). Every issue carries the "
        "identifiers it is about, the error type, whether it is an error or a style "
        "warning, and the status of the fix suggested for it — `proven-fix` when a "
        "theorem says the fix changes no derived fact, `suggested-fix` when the "
        "repair is mechanical, `needs-review` when it is destructive or ambiguous."
    )
    lines.append("")
    lines.append(
        "Each report comes in three forms: `NAME.csv` (one line per issue, for a "
        "spreadsheet), `NAME.html` (a page with a summary by error type) and "
        "`NAME.svg` (a bar chart of the counts)."
    )
    lines.append("")
    lines.append(
        "Two of the reports below are of the hand-written example files in "
        "[`examples/`](../../examples): `defects` and `taxa-defects` are small "
        "bases built to carry one of each kind of problem, so every error type the "
        "tool can report appears somewhere in these tables."
    )
    lines.append("")
    lines.append(
        "The same issues grouped into things to work on — by error type, by file, "
        "by layer and by kind of work, with one CSV per task — are in "
        "[`worklist/`](worklist/README.md), written by `wikidata worklist`."
    )
    lines.append("")
    lines.append("## Per fragment")
    lines.append("")
    lines.append("| report | issues | errors | warnings | error types |")
    lines.append("|---|---:|---:|---:|---|")
    for n in names:
        if n in SPECIAL:
            continue
        rows = per_file[n]
        errs = sum(1 for r in rows if r["severity"] == "error")
        warns = sum(1 for r in rows if r["severity"] == "warning")
        kinds = ", ".join(sorted({r["code"] for r in rows})) or "—"
        lines.append(
            f"| [{n}]({n}.html) ([csv]({n}.csv), [svg]({n}.svg)) | {len(rows)} | "
            f"{errs} | {warns} | {kinds} |"
        )
    lines.append("")
    lines.append("## Aggregates")
    lines.append("")
    lines.append("| report | what it covers | issues | errors | warnings |")
    lines.append("|---|---|---:|---:|---:|")
    covers = {
        "corpus": "every downloaded fragment, in one table",
        "all": "`data/all.wdkb`, the merge of the fragments",
    }
    for n in sorted(SPECIAL):
        if n not in per_file:
            continue
        rows = per_file[n]
        errs = sum(1 for r in rows if r["severity"] == "error")
        warns = sum(1 for r in rows if r["severity"] == "warning")
        lines.append(
            f"| [{n}]({n}.html) ([csv]({n}.csv), [svg]({n}.svg)) | {covers[n]} | "
            f"{len(rows)} | {errs} | {warns} |"
        )
    lines.append("")

    corpus = per_file.get("corpus", [])
    if corpus:
        lines.append("## Error types across the corpus")
        lines.append("")
        lines.append("| error type | severity | status | count | suggested fix |")
        lines.append("|---|---|---|---:|---|")
        counts = Counter(r["code"] for r in corpus)
        first = {}
        for r in corpus:
            first.setdefault(r["code"], r)
        for code, n in counts.most_common():
            r = first[code]
            lines.append(
                f"| `{code}` | {r['severity']} | {r['status']} | {n} | {r['fix']} |"
            )
        lines.append("")

    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(OUT, "README.md"))


if __name__ == "__main__":
    main()
