#!/usr/bin/env python3
"""Builds docs/repairs/README.md from the CSV files `wikidata repairs` wrote.

This script invents nothing: every number below is counted from the rows of the
generated CSV files, which the tool produced from the knowledge bases.  Run it
through scripts/make-repairs.sh, which generates those files first.
"""

import csv
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "docs", "repairs")


def read_rows(path):
    with open(path, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    return [r for r in rows if r.get("code")]


def issue_key(r):
    return (r["code"], r["subject"], r["object"], r["extra"])


def debt_line(name):
    """The `repair debt: A -> B` line the tool wrote at the top of NAME.txt."""
    path = os.path.join(OUT, name + ".txt")
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("repair debt:"):
                text = line[len("repair debt:"):].strip()
                cut = text.find(" if ")
                return text[:cut] if cut >= 0 else text
    return ""


def main():
    names = sorted(f[:-4] for f in os.listdir(OUT) if f.endswith(".csv"))
    per_file = {n: read_rows(os.path.join(OUT, n + ".csv")) for n in names}

    lines = []
    lines.append("# Proposed repairs")
    lines.append("")
    lines.append(
        "Generated by `scripts/make-repairs.sh`, which runs `wikidata repairs` over "
        "the bases listed in it.  For every flagged issue the tool proposes the "
        "changes that would fix it, with the reason for each, and marks the ones a "
        "check certifies: a `proven` candidate removes the issue it is raised for, "
        "adds no error and no warning the base did not already carry, and lowers the "
        "repair debt.  A `rejected` candidate is not wrong — it is a choice for an "
        "editor to make."
    )
    lines.append("")
    lines.append(
        "**Nothing here has been applied.**  The input files are untouched; "
        "`NAME-repaired.wdkb` is the base the recommended changes would produce, "
        "written out only so the two can be compared."
    )
    lines.append("")
    lines.append(
        "Each review comes in three forms: `NAME.csv` (one line per candidate "
        "repair, for a spreadsheet), `NAME.html` (a page with the summary on top) "
        "and `NAME.txt` (a plain text review to paste onto a talk page).  How the "
        "workflow works and what is proved about it is in [../REPAIRS.md](../REPAIRS.md)."
    )
    lines.append("")
    lines.append("## Per base")
    lines.append("")
    lines.append(
        "| review | issues | candidates | recommended | for review | "
        "repair debt if the recommended changes are made |"
    )
    lines.append("|---|---:|---:|---:|---:|---|")
    for n in names:
        rows = per_file[n]
        issues = len({issue_key(r) for r in rows})
        proven = sum(1 for r in rows if r["verdict"] == "proven")
        rejected = sum(1 for r in rows if r["verdict"] != "proven")
        debt = debt_line(n) if rows else "nothing to repair"
        lines.append(
            f"| [{n}]({n}.html) ([csv]({n}.csv), [txt]({n}.txt)) | {issues} | "
            f"{len(rows)} | {proven} | {rejected} | {debt} |"
        )
    lines.append("")

    lines.append("## What the candidates are for")
    lines.append("")
    lines.append("| error type | candidates | recommended |")
    lines.append("|---|---:|---:|")
    codes = Counter()
    proven_codes = Counter()
    for rows in per_file.values():
        for r in rows:
            codes[r["code"]] += 1
            if r["verdict"] == "proven":
                proven_codes[r["code"]] += 1
    for code in sorted(codes):
        lines.append(f"| `{code}` | {codes[code]} | {proven_codes[code]} |")
    lines.append("")

    total = sum(len(r) for r in per_file.values())
    total_proven = sum(proven_codes.values())
    lines.append(
        f"Over these {len(names)} bases the tool proposes {total} candidate "
        f"repairs, of which {total_proven} are recommended and "
        f"{total - total_proven} are left for a person to decide."
    )
    lines.append("")

    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote docs/repairs/README.md")


if __name__ == "__main__":
    main()
